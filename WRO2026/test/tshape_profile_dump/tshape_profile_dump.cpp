/**
 * @file tshape_profile_dump.cpp
 * @brief Host golden-vector dump for `TShapeProfilePolicy.h` (issue #130, T3).
 *
 * Includes the pure, Arduino-free `TShapeProfilePolicy.h` header PLUS the REAL firmware
 * `Config::TSHAPE_*` / `Config::PWM_MIN_MAGNITUDE` constants (`WRO2026/config/ConfigGlobal.h` +
 * `WRO2026/config/ConfigDrive.h` — both pure `<stdint.h>`-only `constexpr`, no Arduino surface,
 * so they are directly host-includable with zero mocking). For a curated set of
 * `(dist, cruise, start, end, accel)` vectors it calls `resolveTShapeRamps` once and
 * `tShapeSpeedAt` at several `traveled` sample points, then prints the whole set as JSON on
 * stdout.
 *
 * This binary is DELIBERATELY not a self-asserting ctest target — see
 * `tshape_profile_freshness.cmake`, which drives it twice (once to a temp file, once already
 * committed as `tools/path_planner/tests/fixtures/tshape_profile_goldens.json`) and byte-compares
 * the two. That comparison IS the ctest — the "executable tether" the plan calls for: a firmware
 * retune that changes `Config::TSHAPE_*` or the policy math changes this program's stdout, which
 * then diverges from the committed fixture and fails CI until the fixture is regenerated.
 *
 * JSON precision (load-bearing): every float column (`dist`, `accel`, `accelCm`, `decelCm`) is
 * printed with `%.9g` — enough decimal digits that a `float` -> ASCII -> `float`/`numpy.float32`
 * round trip reproduces the EXACT same 32-bit pattern (9 significant digits is the documented
 * upper bound for a `float`'s round-trip guarantee). We never widen to `double` math before
 * printing; the values themselves are already the `float`s the policy returned, just formatted
 * with headroom so printing loses no bits.
 *
 * Line endings (cross-OS, load-bearing): stdout is forced into BINARY mode on Windows/MSVC
 * (`_setmode(_fileno(stdout), _O_BINARY)`) so every `\n` this program writes stays a bare LF
 * instead of being translated to CRLF by the C runtime's default text-mode stdout. That keeps
 * the generated bytes byte-identical on Windows, macOS, and Linux, so the committed fixture
 * (git-normalized to LF via `.gitattributes: *.json text eol=lf`) byte-matches a fresh Windows
 * run and the `tshape_profile_freshness` gate stays green on every teammate's OS. On POSIX the
 * `_setmode` call is a no-op (stdout never translates), so the guard is Windows-only.
 *
 * JSON shape (Contracts -> "Golden-vector JSON (host <-> pytest)", `tools/path_planner/tests/
 * fixtures/tshape_profile_goldens.json`):
 *   [
 *     { "dist": <float>, "cruise": <int>, "start": <int>, "end": <int>, "accel": <float>,
 *       "expect": { "accelCm": <float>, "decelCm": <float>, "peakPwm": <int>,
 *                   "pwm_at": [ {"traveled": <float>, "pwm": <int>}, ... ] } },
 *     ...
 *   ]
 * `pwm_at` makes the queried traveled-distance EXPLICIT per sample (rather than an implicit
 * fixed grid) so the Python parity test (T6 / TC1) can call `resolve_tshape_ramps` /
 * `tShapeSpeedAt`'s Python mirror at EXACTLY these points with each vector's own columns.
 */

#include <cstdio>
#include <string>
#include <vector>

// Windows/MSVC only: pull in `_setmode` / `_fileno` / `_O_BINARY` so main() can force stdout
// into binary mode (see the file-level "Line endings" note). Guarded by `_WIN32` so the POSIX
// build (g++ / clang on Linux + macOS — where stdout never translates) never sees these headers.
#if defined(_WIN32)
#include <fcntl.h>
#include <io.h>
#endif

#include "../../config/ConfigDrive.h"
#include "../../config/ConfigGlobal.h"
#include "../../src/drive/TShapeProfilePolicy.h"

namespace
{
    /**
     * @brief One golden-vector input: the five `resolveTShapeRamps` arguments plus a curated
     *        list of `traveled` query points fed to `tShapeSpeedAt` afterward.
     */
    struct GoldenCase
    {
        const char*        label;    ///< Human-readable regime tag (comment only, not emitted).
        float              dist;
        int16_t            cruise;
        int16_t            start;
        int16_t            end;
        float              accel;
        std::vector<float> travel;    ///< `traveled` sample points (cm), any order.
    };

    /**
     * @brief Format a `float` as a JSON number with enough precision to round-trip the exact
     *        32-bit value (see the file-level doc comment). `%.9g` mirrors the well-known
     *        `FLT_DECIMAL_DIG == 9` round-trip bound for IEEE-754 single precision.
     */
    std::string floatToJson(float v)
    {
        char buf[48];
        std::snprintf(buf, sizeof(buf), "%.9g", static_cast<double>(v));
        return std::string(buf);
    }

    /**
     * @brief Build the curated golden-vector set. Coverage (see the T3 task spec):
     *   - flat/no-ramp-shaped short move (< TSHAPE_MIN_MOVE_CM)   -> triangle collapse, tiny peak.
     *   - triangular regime (ramps don't fit)                    -> peak < cruise, no plateau.
     *   - full trapezoid (ramps fit with room for a plateau)     -> accelCm/decelCm + flat peak.
     *   - reverse hop (negative cruise/start/end)                -> sign-aware clamps + reverse ramp.
     *   - no-brake case (end == cruise)                          -> no decel ramp at all.
     *   - stop case (end == 0)                                   -> decel ramp to rest.
     *   - epsilon edge (start almost equal to cruise)             -> no-ramp epsilon boundary.
     *   - ramp-min / ramp-max clamp boundaries                    -> per-side floor/ceiling clamp.
     * `travel` samples span the accel phase, the plateau (where one exists), the decel phase,
     * and — for a stop case — the deadband-floor crawl tail near move end.
     */
    std::vector<GoldenCase> buildGoldenCases()
    {
        using Config::TSHAPE_ACCEL_PWM_PER_CM;
        using Config::TSHAPE_END_SPEED;
        using Config::TSHAPE_START_SPEED;

        std::vector<GoldenCase> cases;

        // ---- 1. Short move (< TSHAPE_MIN_MOVE_CM = 5 cm): 3 cm @ cruise 85, default
        //         start/end. The un-gated policy still resolves this (the >=5cm gate is a
        //         CALLER decision in Drive.h, not inside the policy) — the ramps massively
        //         over-run 3 cm so this collapses through the triangle branch with a small
        //         peak. Samples: start, mid, near-end.
        cases.push_back({"short_3cm_triangle_collapse",
                          3.0f,
                          85,
                          TSHAPE_START_SPEED,
                          TSHAPE_END_SPEED,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 1.0f, 1.5f, 2.5f, 3.0f}});

        // ---- 2. Triangular regime: 12 cm @ cruise 85 (start=floor, end=0). Per-side RAW ramp
        //         (pre-clamp, which is what the triangle test runs against) = (85-50)/5 = 7 cm
        //         and (85-0)/5 = 17 cm; 7+17=24 > 12 -> triangle fallback fires: peak reduces to
        //         (start+end+cruise)/3 = 45 < cruise (no plateau), ramps rescale to sum to 12
        //         (3.5 + 8.5), and the half-of-total cap then trims the oversized decel side
        //         down to 6 cm (12*0.5) — exercising BOTH the triangle collapse AND the
        //         asymmetric half-cap trim documented in TShapeProfilePolicy.h.
        cases.push_back({"triangular_12cm",
                          12.0f,
                          85,
                          TSHAPE_START_SPEED,
                          TSHAPE_END_SPEED,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 3.0f, 6.0f, 9.0f, 12.0f}});

        // ---- 3. Full trapezoid: 40 cm @ cruise 85 (start=floor, end=0). accelCm = 7 cm,
        //         decelCm = 17 cm (both within [2,20]); 7+17=24 <= 40 -> plateau of 16 cm.
        cases.push_back({"full_trapezoid_40cm",
                          40.0f,
                          85,
                          TSHAPE_START_SPEED,
                          TSHAPE_END_SPEED,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 3.5f, 7.0f, 15.0f, 23.0f, 30.0f, 38.0f, 40.0f}});

        // ---- 4. Reverse hop: negative cruise/start/end (dead-reckon backward). Exercises the
        //         sign-aware peak clamp (`peak < cruise && cruise < 0`) and a reverse ramp.
        //         accelCm = |(-85)-(-50)|/5 = 7 cm, decelCm = |(-85)-0|/5 = 17 cm; 24 <= 30cm
        //         plateau of 6 cm.
        cases.push_back({"reverse_hop_30cm",
                          30.0f,
                          -85,
                          -50,
                          0,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 3.5f, 7.0f, 15.0f, 23.0f, 28.0f, 30.0f}});

        // ---- 5. No-brake case: end == cruise (chained move; ConfigDrive.h's setBrake(false)
        //         default rule resolves endSpeed=cruise, which the CALLER applies — this vector
        //         exercises the POLICY directly with that already-resolved endSpeed). decelCm
        //         resolves to 0 (no-ramp epsilon: |cruise-end| = 0 < epsilon) -> no decel ramp,
        //         PWM holds at peak all the way to move end.
        cases.push_back({"no_brake_end_eq_cruise_20cm",
                          20.0f,
                          85,
                          TSHAPE_START_SPEED,
                          85,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 5.0f, 7.0f, 15.0f, 20.0f}});

        // ---- 6. Stop case: end == 0, long move (30 cm) so the decel ramp + a deadband-floor
        //         crawl tail both fit before move end. accelCm=7cm, decelCm=17cm; 24<=30cm ->
        //         6cm plateau. Samples include a point inside the decel ramp where the
        //         interpolated PWM is already below PWM_MIN_MAGNITUDE (the floor-crawl regime
        //         downstream in `profile.py` / `Drive.cpp`'s `deadbandSnap` — the RAW
        //         pre-snap value here is exactly what `tShapeSpeedAt` returns, un-snapped).
        cases.push_back({"stop_case_30cm",
                          30.0f,
                          85,
                          TSHAPE_START_SPEED,
                          TSHAPE_END_SPEED,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 3.5f, 7.0f, 13.0f, 20.0f, 27.0f, 29.0f, 30.0f}});

        // ---- 7. Epsilon edge: start speed within TSHAPE_NO_RAMP_EPSILON_PWM (2) of cruise ->
        //         the accel-side ramp resolves to exactly 0.0f (strict `<` no-ramp path), so
        //         the move starts flat at peak immediately. cruise=85, start=84 (delta=1 < 2).
        cases.push_back({"epsilon_edge_start_near_cruise",
                          20.0f,
                          85,
                          84,
                          TSHAPE_END_SPEED,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 1.0f, 10.0f, 20.0f}});

        // ---- 8. Ramp-min clamp boundary: cruise/start/end chosen so the RAW per-side ramp
        //         distance is below TSHAPE_RAMP_MIN_CM (2 cm) and gets floored UP to it.
        //         cruise=60, start=55 (delta=5, raw=5/5=1cm < rampMin=2cm -> clamps to 2cm);
        //         end=0 (raw=60/5=12cm, within [2,20], no clamp). Long move (30cm) keeps the
        //         trapezoid path so the clamp is directly observable in accelCm.
        cases.push_back({"ramp_min_clamp",
                          30.0f,
                          60,
                          55,
                          0,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 1.0f, 2.0f, 10.0f, 20.0f, 30.0f}});

        // ---- 9. Ramp-max clamp boundary: raw per-side ramp distance exceeds
        //         TSHAPE_RAMP_MAX_CM (20 cm) and gets capped down to it. cruise=90, start=0
        //         (accel side: delta=90, raw=90/5=18cm, within [2,20], NOT clamped); end=-40
        //         (decel side: delta=130, raw=130/5=26cm > 20cm ceiling -> clamps down to 20cm).
        //         Long move (60cm) so 18(accel)+20(decel,clamped)=38 <= 60cm keeps a plateau, so
        //         the clamp is directly observable in decelCm without any triangle interaction.
        cases.push_back({"ramp_max_clamp",
                          60.0f,
                          90,
                          0,
                          -40,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 10.0f, 20.0f, 30.0f, 40.0f, 50.0f, 60.0f}});

        // ---- 10. REVERSE-triangle with the NEGATIVE sign-clamp firing. Tethers the
        //          `peak < cruise && cruise < 0` branch of the triangle fallback (untested by
        //          case #4, whose reverse hop is a full trapezoid). cruise=-50, start=-90,
        //          end=-90 -> raw ramps |(-50)-(-90)|/5 = 8 cm each (sum 16 > dist 10 -> triangle
        //          fires). Averaged peak = (start+end+cruise)/3 = (-90-90-50)/3 = -76 (int32
        //          truncating divide toward zero), which is MORE negative than cruise=-50, so the
        //          negative sign-clamp floors it back UP to cruise (-50). Ramps rescale to sum to
        //          10 (5 + 5), then the half-of-total cap holds them at 5 cm each (10*0.5).
        //          Expect: accelCm=5, decelCm=5, peakPwm=-50. Samples span the reverse accel and
        //          decel ramps (peak sits at the midpoint of a pure triangle).
        cases.push_back({"reverse_triangle_neg_clamp",
                          10.0f,
                          -50,
                          -90,
                          -90,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 2.5f, 5.0f, 7.5f, 10.0f}});

        // ---- 11. POSITIVE triangle-peak clamp firing. Tethers the `peak > cruise && cruise >= 0`
        //          branch — a case where start AND end both sit ABOVE cruise (a decel-in /
        //          accel-out move), so the averaged peak exceeds the requested cruise and must be
        //          clamped DOWN to it. cruise=50, start=90, end=90 -> raw ramps |50-90|/5 = 8 cm
        //          each (sum 16 > dist 10 -> triangle fires). Averaged peak = (90+90+50)/3 = 76 >
        //          cruise=50, so the positive clamp floors it DOWN to cruise (50). Ramps rescale
        //          to 5 + 5, then the half-cap holds them at 5 cm each. Expect: accelCm=5,
        //          decelCm=5, peakPwm=50. (90 is within the valid PWM range: SPEED_FAST=90 <
        //          PWM_MAX=95.)
        cases.push_back({"triangle_pos_peak_clamp",
                          10.0f,
                          50,
                          90,
                          90,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          {0.0f, 2.5f, 5.0f, 7.5f, 10.0f}});

        return cases;
    }

    /**
     * @brief Print one `GoldenCase` + its resolved ramps/peak/pwm_at samples as one JSON object.
     */
    void printCase(const GoldenCase& c, bool isLast)
    {
        using Config::TSHAPE_NO_RAMP_EPSILON_PWM;
        using Config::TSHAPE_RAMP_MAX_CM;
        using Config::TSHAPE_RAMP_MIN_CM;

        const TShapeRamps ramps = resolveTShapeRamps(c.dist,
                                                      c.cruise,
                                                      c.start,
                                                      c.end,
                                                      c.accel,
                                                      TSHAPE_RAMP_MIN_CM,
                                                      TSHAPE_RAMP_MAX_CM,
                                                      TSHAPE_NO_RAMP_EPSILON_PWM);

        std::printf("  {\n");
        std::printf("    \"dist\": %s,\n", floatToJson(c.dist).c_str());
        std::printf("    \"cruise\": %d,\n", static_cast<int>(c.cruise));
        std::printf("    \"start\": %d,\n", static_cast<int>(c.start));
        std::printf("    \"end\": %d,\n", static_cast<int>(c.end));
        std::printf("    \"accel\": %s,\n", floatToJson(c.accel).c_str());
        std::printf("    \"expect\": {\n");
        std::printf("      \"accelCm\": %s,\n", floatToJson(ramps.accelCm).c_str());
        std::printf("      \"decelCm\": %s,\n", floatToJson(ramps.decelCm).c_str());
        std::printf("      \"peakPwm\": %d,\n", static_cast<int>(ramps.peakPwm));
        std::printf("      \"pwm_at\": [\n");
        for (size_t i = 0; i < c.travel.size(); ++i)
        {
            const float   traveled = c.travel[i];
            const int16_t pwm      = tShapeSpeedAt(traveled, c.dist, ramps, c.start, c.end);
            std::printf("        {\"traveled\": %s, \"pwm\": %d}%s\n",
                        floatToJson(traveled).c_str(),
                        static_cast<int>(pwm),
                        (i + 1 < c.travel.size()) ? "," : "");
        }
        std::printf("      ]\n");
        std::printf("    }\n");
        std::printf("  }%s\n", isLast ? "" : ",");
    }
}    // namespace

int main()
{
#if defined(_WIN32)
    // Force stdout to binary so `\n` is emitted as a bare LF, not CRLF (cross-OS byte-identity
    // with the LF-normalized committed fixture — see the file-level "Line endings" note).
    _setmode(_fileno(stdout), _O_BINARY);
#endif

    const std::vector<GoldenCase> cases = buildGoldenCases();

    std::printf("[\n");
    for (size_t i = 0; i < cases.size(); ++i)
    {
        printCase(cases[i], i + 1 == cases.size());
    }
    std::printf("]\n");

    return 0;
}
