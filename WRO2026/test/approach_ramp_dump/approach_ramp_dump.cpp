/**
 * @file approach_ramp_dump.cpp
 * @brief Host golden-vector dump for `ApproachRampPolicy.h` (2026-07-17
 *        anticipatory-line-approach-ramp plan, T3).
 *
 * Includes the pure, Arduino-free `ApproachRampPolicy.h` header PLUS the REAL firmware
 * `Config::TSHAPE_*` / `Config::PWM_MOVING_MIN` / `Config::LINE_APPROACH_*` / `Config::SPEED_*`
 * constants (`WRO2026/config/ConfigGlobal.h` + `WRO2026/config/ConfigDrive.h` — both pure
 * `<stdint.h>`-only `constexpr`, no Arduino surface, so they are directly host-includable with
 * zero mocking). For a curated set of `(predictedCm, marginCm, maxMarginCm, cruiseMag, floorMag,
 * accel, rampMin, rampMax, noRampEps, minMoveCm)` vectors it calls `resolveApproachSchedule` once
 * and `approachSpeedAt` at several `traveled` sample points, then prints the whole set as JSON on
 * stdout.
 *
 * This binary is DELIBERATELY not a self-asserting ctest target — see
 * `approach_ramp_freshness.cmake`, which drives it twice (once to a temp file, once already
 * committed as `tools/path_planner/tests/fixtures/approach_ramp_goldens.json`) and byte-compares
 * the two. That comparison IS the ctest — the "executable tether" (mirrors
 * `tshape_profile_dump`): a firmware retune that changes
 * `Config::TSHAPE_*` / `Config::LINE_APPROACH_*` or a change to the policy math changes this
 * program's stdout, which then diverges from the committed fixture and fails CI until the
 * fixture is regenerated. Consumed by the Python cross-language test (T5 / TC13).
 *
 * JSON precision (load-bearing): every float column (`predictedCm`, `marginCm`, `maxMarginCm`,
 * `accel`, `rampMin`, `rampMax`, `minMoveCm`, `rampStartCm`, `floorStartCm`, `overrunLimitCm`,
 * `traveled`) is printed with `%.9g` — enough decimal digits that a `float` -> ASCII ->
 * `float`/`numpy.float32` round trip reproduces the EXACT same 32-bit pattern (9 significant
 * digits is the documented upper bound for a `float`'s round-trip guarantee, `FLT_DECIMAL_DIG ==
 * 9`). We never widen to `double` math before printing; the values themselves are already the
 * `float`s the policy returned, just formatted with headroom so printing loses no bits.
 *
 * Line endings (cross-OS, load-bearing): stdout is forced into BINARY mode on Windows/MSVC
 * (`_setmode(_fileno(stdout), _O_BINARY)`) so every `\n` this program writes stays a bare LF
 * instead of being translated to CRLF by the C runtime's default text-mode stdout. That keeps
 * the generated bytes byte-identical on Windows, macOS, and Linux, so the committed fixture
 * (git-normalized to LF via `.gitattributes: *.json text eol=lf`) byte-matches a fresh Windows
 * run and the `approach_ramp_freshness` gate stays green on every teammate's OS. On POSIX the
 * `_setmode` call is a no-op (stdout never translates), so the guard is Windows-only.
 *
 * JSON shape (`tools/path_planner/tests/fixtures/approach_ramp_goldens.json`):
 *   [
 *     { "label": <string>,
 *       "predictedCm": <float>, "marginCm": <float>, "maxMarginCm": <float>,
 *       "cruiseMag": <int>, "floorMag": <int>,
 *       "accel": <float>, "rampMin": <float>, "rampMax": <float>,
 *       "noRampEps": <int>, "minMoveCm": <float>,
 *       "expect": {
 *         "rampStartCm": <float>, "floorStartCm": <float>, "overrunLimitCm": <float>,
 *         "cruiseMag": <int>, "floorMag": <int>, "active": <bool>,
 *         "speed_at": [ {"traveled": <float>, "pwmMag": <int>, "phase": <string>}, ... ]
 *       }
 *     },
 *     ...
 *   ]
 * `expect.rampStartCm/floorStartCm/overrunLimitCm/cruiseMag/floorMag/active` mirror the
 * `ApproachSchedule` field order exactly (the T2 contract) so the Python mirror can compare
 * field-by-field. `speed_at` makes the queried traveled-distance EXPLICIT per sample (rather than
 * an implicit fixed grid) so the Python parity test (T5 / TC13) can call
 * `resolve_approach_schedule` / `approach_speed_at`'s Python mirror at EXACTLY these points with
 * each vector's own columns. A DEGENERATE vector (`expect.active == false`) emits an EMPTY
 * `speed_at` array — the header's own contract says `approachSpeedAt` must not be invoked on a
 * schedule with `active == false` (the boundaries are meaningless), so the dump mirrors that by
 * never calling it for those vectors.
 */

#include <cstdio>
#include <string>
#include <vector>

// Windows/MSVC only: pull in `_setmode` / `_fileno` / `_O_BINARY` so main() can force stdout
// into binary mode (see the file-level "Line endings" note). Guarded by `_WIN32` so the POSIX
// build (g++ / clang on Linux + macOS — where stdout never translates) never sees these headers.
#if defined(_WIN32)
#include <fcntl.h>
#include <io.h>
#endif

#include "../../config/ConfigDrive.h"
#include "../../config/ConfigGlobal.h"
#include "../../src/drive/ApproachRampPolicy.h"

namespace
{
    /**
     * @brief One golden-vector input: the ten `resolveApproachSchedule` arguments plus a
     *        curated list of `traveled` query points fed to `approachSpeedAt` afterward
     *        (ignored when the schedule degrades to `active == false`).
     */
    struct GoldenCase
    {
        const char*        label;    ///< Human-readable regime tag (emitted for readability).
        float              predictedCm;
        float              marginCm;
        float              maxMarginCm;
        int16_t            cruiseMag;
        int16_t            floorMag;
        float              accel;
        float              rampMin;
        float              rampMax;
        int16_t            noRampEps;
        float              minMoveCm;
        std::vector<float> travel;    ///< `traveled` sample points (cm), any order.
    };

    /**
     * @brief Format a `float` as a JSON number with enough precision to round-trip the exact
     *        32-bit value (see the file-level doc comment). `%.9g` mirrors the well-known
     *        `FLT_DECIMAL_DIG == 9` round-trip bound for IEEE-754 single precision.
     */
    std::string floatToJson(float v)
    {
        char buf[48];
        std::snprintf(buf, sizeof(buf), "%.9g", static_cast<double>(v));
        return std::string(buf);
    }

    /** @brief Stable string tag for an `ApproachPhase`, matched byte-for-byte by the Python mirror. */
    const char* phaseName(ApproachPhase p)
    {
        switch (p)
        {
            case ApproachPhase::CRUISE:
                return "CRUISE";
            case ApproachPhase::RAMP:
                return "RAMP";
            case ApproachPhase::FLOOR_HOLD:
                return "FLOOR_HOLD";
            case ApproachPhase::OVERRUN:
                return "OVERRUN";
        }
        return "?";
    }

    /**
     * @brief Build the curated golden-vector set. Coverage (see the T3 task spec / TC1, TC7,
     *        TC17):
     *   - nominal forward hop, cruise=SPEED_NORMAL(70)/floor=PWM_MOVING_MIN(30) -> full 4-phase
     *     sweep (CRUISE -> RAMP -> FLOOR_HOLD -> OVERRUN).
     *   - nominal forward hop, cruise=SPEED_FAST(90)/floor=30 -> a longer ramp, so the coverage
     *     isn't an artifact of one specific ramp length.
     *   - a `predictedCm`-shifted TWIN of the first vector (same cruise/floor/margins, predicted
     *     +20cm) — the boundaries and per-offset `speed_at` samples below are the FIRST vector's
     *     shifted by the identical +20cm delta, making the "no internal offset math" contract
     *     (TC17) visually verifiable straight from the committed JSON.
     *   - degrade: predictedCm below TSHAPE_MIN_MOVE_CM -> active=false, empty speed_at.
     *   - degrade: predictedCm clears minMoveCm but rampStartCm <= 0 -> active=false, empty
     *     speed_at (a DIFFERENT degrade path than the vector above).
     *   - boundary: predictedCm == minMoveCm exactly (cruiseMag == floorMag collapses the ramp to
     *     0cm so this isolates the minMoveCm branch) -> active=true (strict `<`, not `<=`).
     *   - boundary: predictedCm just below minMoveCm, same setup -> active=false.
     */
    std::vector<GoldenCase> buildGoldenCases()
    {
        using Config::LINE_APPROACH_MARGIN_CM;
        using Config::LINE_APPROACH_MAX_MARGIN_CM;
        using Config::PWM_MOVING_MIN;
        using Config::SPEED_FAST;
        using Config::SPEED_NORMAL;
        using Config::TSHAPE_ACCEL_PWM_PER_CM;
        using Config::TSHAPE_MIN_MOVE_CM;
        using Config::TSHAPE_NO_RAMP_EPSILON_PWM;
        using Config::TSHAPE_RAMP_MAX_CM;
        using Config::TSHAPE_RAMP_MIN_CM;

        std::vector<GoldenCase> cases;

        // ---- 1. Nominal forward hop: cruise=70/floor=30, predicted=50cm. rampLenCm=10cm ->
        //         rampStartCm=36, floorStartCm=46, overrunLimitCm=65. Samples span all 4 phases.
        cases.push_back({"nominal_cruise70_predicted50",
                          50.0f,
                          LINE_APPROACH_MARGIN_CM,
                          LINE_APPROACH_MAX_MARGIN_CM,
                          SPEED_NORMAL,
                          PWM_MOVING_MIN,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          TSHAPE_RAMP_MIN_CM,
                          TSHAPE_RAMP_MAX_CM,
                          TSHAPE_NO_RAMP_EPSILON_PWM,
                          TSHAPE_MIN_MOVE_CM,
                          {0.0f, 20.0f, 30.0f, 36.0f, 38.0f, 41.0f, 44.0f, 45.9f, 46.0f, 50.0f,
                           60.0f, 64.9f, 65.0f, 70.0f, 90.0f}});

        // ---- 2. Nominal forward hop: cruise=90/floor=30, predicted=80cm. rampLenCm=15cm ->
        //         rampStartCm=61, floorStartCm=76, overrunLimitCm=95. A longer ramp than #1.
        cases.push_back({"nominal_cruise90_predicted80",
                          80.0f,
                          LINE_APPROACH_MARGIN_CM,
                          LINE_APPROACH_MAX_MARGIN_CM,
                          SPEED_FAST,
                          PWM_MOVING_MIN,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          TSHAPE_RAMP_MIN_CM,
                          TSHAPE_RAMP_MAX_CM,
                          TSHAPE_NO_RAMP_EPSILON_PWM,
                          TSHAPE_MIN_MOVE_CM,
                          {0.0f, 30.0f, 55.0f, 61.0f, 65.0f, 70.0f, 75.0f, 75.9f, 76.0f, 80.0f,
                           90.0f, 94.9f, 95.0f, 100.0f, 120.0f}});

        // ---- 3. TC17 twin of #1: predicted=70cm (= #1's 50cm + 20cm), same cruise/floor/margins.
        //         rampStartCm=56, floorStartCm=66, overrunLimitCm=85 — each exactly #1's boundary
        //         + 20cm. `speed_at` samples are #1's samples + 20cm, so the resolved `pwmMag`/
        //         `phase` at sample i here must equal #1's sample i (TC17: no offset math).
        cases.push_back({"nominal_cruise70_predicted70_tc17_shift",
                          70.0f,
                          LINE_APPROACH_MARGIN_CM,
                          LINE_APPROACH_MAX_MARGIN_CM,
                          SPEED_NORMAL,
                          PWM_MOVING_MIN,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          TSHAPE_RAMP_MIN_CM,
                          TSHAPE_RAMP_MAX_CM,
                          TSHAPE_NO_RAMP_EPSILON_PWM,
                          TSHAPE_MIN_MOVE_CM,
                          {20.0f, 40.0f, 50.0f, 56.0f, 58.0f, 61.0f, 64.0f, 65.9f, 66.0f, 70.0f,
                           80.0f, 84.9f, 85.0f, 90.0f, 110.0f}});

        // ---- 4. Degrade: predictedCm(3) < minMoveCm(5) -> active=false. Empty speed_at.
        cases.push_back({"degrade_short_hop_below_min_move",
                          3.0f,
                          LINE_APPROACH_MARGIN_CM,
                          LINE_APPROACH_MAX_MARGIN_CM,
                          SPEED_NORMAL,
                          PWM_MOVING_MIN,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          TSHAPE_RAMP_MIN_CM,
                          TSHAPE_RAMP_MAX_CM,
                          TSHAPE_NO_RAMP_EPSILON_PWM,
                          TSHAPE_MIN_MOVE_CM,
                          {}});

        // ---- 5. Degrade: predictedCm(10) clears minMoveCm(5) on its own, but cruise=90/floor=30
        //         (rampLenCm=15) leaves rampStartCm = (10-4)-15 = -9 <= 0 -> active=false. A
        //         DIFFERENT degrade path than #4. Empty speed_at.
        cases.push_back({"degrade_ramp_start_non_positive",
                          10.0f,
                          LINE_APPROACH_MARGIN_CM,
                          LINE_APPROACH_MAX_MARGIN_CM,
                          SPEED_FAST,
                          PWM_MOVING_MIN,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          TSHAPE_RAMP_MIN_CM,
                          TSHAPE_RAMP_MAX_CM,
                          TSHAPE_NO_RAMP_EPSILON_PWM,
                          TSHAPE_MIN_MOVE_CM,
                          {}});

        // ---- 6. Boundary: predictedCm == minMoveCm(5) exactly. cruiseMag == floorMag(30, ==
        //         PWM_MOVING_MIN) collapses rampLenCm to 0 (deltaMag(0) < noRampEps), isolating
        //         the minMoveCm branch from the rampStartCm branch. Strict `<` => NOT degraded.
        cases.push_back({"boundary_min_move_exact",
                          TSHAPE_MIN_MOVE_CM,
                          LINE_APPROACH_MARGIN_CM,
                          LINE_APPROACH_MAX_MARGIN_CM,
                          PWM_MOVING_MIN,
                          PWM_MOVING_MIN,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          TSHAPE_RAMP_MIN_CM,
                          TSHAPE_RAMP_MAX_CM,
                          TSHAPE_NO_RAMP_EPSILON_PWM,
                          TSHAPE_MIN_MOVE_CM,
                          {0.0f, 0.5f, 1.0f, 2.0f, 4.0f, 5.0f, 15.0f, 16.0f}});

        // ---- 7. Boundary: predictedCm just below minMoveCm, same setup as #6 -> active=false.
        cases.push_back({"boundary_min_move_just_below",
                          TSHAPE_MIN_MOVE_CM - 0.001f,
                          LINE_APPROACH_MARGIN_CM,
                          LINE_APPROACH_MAX_MARGIN_CM,
                          PWM_MOVING_MIN,
                          PWM_MOVING_MIN,
                          TSHAPE_ACCEL_PWM_PER_CM,
                          TSHAPE_RAMP_MIN_CM,
                          TSHAPE_RAMP_MAX_CM,
                          TSHAPE_NO_RAMP_EPSILON_PWM,
                          TSHAPE_MIN_MOVE_CM,
                          {}});

        return cases;
    }

    /**
     * @brief Print one `GoldenCase` + its resolved schedule/speed_at samples as one JSON object.
     */
    void printCase(const GoldenCase& c, bool isLast)
    {
        const ApproachSchedule s = resolveApproachSchedule(
            c.predictedCm, c.marginCm, c.maxMarginCm, c.cruiseMag, c.floorMag, c.accel, c.rampMin,
            c.rampMax, c.noRampEps, c.minMoveCm);

        std::printf("  {\n");
        std::printf("    \"label\": \"%s\",\n", c.label);
        std::printf("    \"predictedCm\": %s,\n", floatToJson(c.predictedCm).c_str());
        std::printf("    \"marginCm\": %s,\n", floatToJson(c.marginCm).c_str());
        std::printf("    \"maxMarginCm\": %s,\n", floatToJson(c.maxMarginCm).c_str());
        std::printf("    \"cruiseMag\": %d,\n", static_cast<int>(c.cruiseMag));
        std::printf("    \"floorMag\": %d,\n", static_cast<int>(c.floorMag));
        std::printf("    \"accel\": %s,\n", floatToJson(c.accel).c_str());
        std::printf("    \"rampMin\": %s,\n", floatToJson(c.rampMin).c_str());
        std::printf("    \"rampMax\": %s,\n", floatToJson(c.rampMax).c_str());
        std::printf("    \"noRampEps\": %d,\n", static_cast<int>(c.noRampEps));
        std::printf("    \"minMoveCm\": %s,\n", floatToJson(c.minMoveCm).c_str());
        std::printf("    \"expect\": {\n");
        std::printf("      \"rampStartCm\": %s,\n", floatToJson(s.rampStartCm).c_str());
        std::printf("      \"floorStartCm\": %s,\n", floatToJson(s.floorStartCm).c_str());
        std::printf("      \"overrunLimitCm\": %s,\n", floatToJson(s.overrunLimitCm).c_str());
        std::printf("      \"cruiseMag\": %d,\n", static_cast<int>(s.cruiseMag));
        std::printf("      \"floorMag\": %d,\n", static_cast<int>(s.floorMag));
        std::printf("      \"active\": %s,\n", s.active ? "true" : "false");
        std::printf("      \"speed_at\": [");

        // The header's contract forbids calling `approachSpeedAt` on a degenerate schedule — the
        // boundaries are meaningless — so a degraded vector emits an empty array here.
        if (s.active && !c.travel.empty())
        {
            std::printf("\n");
            for (size_t i = 0; i < c.travel.size(); ++i)
            {
                const float         traveled = c.travel[i];
                const ApproachSpeed speed    = approachSpeedAt(s, traveled);
                std::printf("        {\"traveled\": %s, \"pwmMag\": %d, \"phase\": \"%s\"}%s\n",
                            floatToJson(traveled).c_str(), static_cast<int>(speed.pwmMag),
                            phaseName(speed.phase), (i + 1 < c.travel.size()) ? "," : "");
            }
            std::printf("      ]\n");
        }
        else
        {
            std::printf("]\n");
        }
        std::printf("    }\n");
        std::printf("  }%s\n", isLast ? "" : ",");
    }
}    // namespace

int main()
{
#if defined(_WIN32)
    // Force stdout to binary so `\n` is emitted as a bare LF, not CRLF (cross-OS byte-identity
    // with the LF-normalized committed fixture — see the file-level "Line endings" note).
    _setmode(_fileno(stdout), _O_BINARY);
#endif

    const std::vector<GoldenCase> cases = buildGoldenCases();

    std::printf("[\n");
    for (size_t i = 0; i < cases.size(); ++i)
    {
        printCase(cases[i], i + 1 == cases.size());
    }
    std::printf("]\n");

    return 0;
}
